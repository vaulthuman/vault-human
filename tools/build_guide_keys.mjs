// Builds the Vault Guide Key library from src/data/letters.js.
// Rule (Russ): no source person's name or known tagline in public content.
// Conservative: any sentence with a capitalized word that is not on the allowlist
// (or with quotes/italics) is dropped. Keys left with no clean idea or practice are skipped.
import fs from 'node:fs';
import { letters as L2 } from '../src/data/letters.js';
import { letters as K } from '../src/data/keys.js';
const slugOf = new Map(L2.map(l => [l.vault + '|' + l.title.toLowerCase(), l.slug]));
const letters = K.map(k => ({ ...k, slug: slugOf.get(k.vault + '|' + k.title.toLowerCase()), body: k.paras.map(t => ({ t })) })).filter(k => k.slug);
const strip = s => s.replace(/<[^>]+>/g, '').replace(/\*\*/g, '').replace(/\s+/g, ' ').trim();
const ALLOW = new Set(('I Vault Human Key Keys Russ Today Tomorrow Monday Tuesday Wednesday Thursday Friday Saturday Sunday ' +
  'January February March April May June July August September October November December Outside Write Pick Choose Do Find Take Set ' +
  'Before After At In On For If When Then And But Or So No Not One Two Three Five Ten Twenty The A An This That These Those It Its ' +
  'You Your We Our My Me Every Each Once Next Last First Go Put Say Ask Tell Look Read Sit Stand Walk Name Notice Keep Make Give ' +
  'Start Stop End Open Close Spend Count Leave Let Try Use Turn Breathe Drink Eat Sleep Call Text Send Mark Circle List Note ' +
  'Mind Body Heart Healing Rhythm Freedom Future Service Sharing Awareness Meaning Circle Outside Twenty Thirty Minutes').split(/\s+/));
const sentences = t => (t.match(/[^.!?]+[.!?]+/g) || [t]).map(x => x.trim()).filter(Boolean);
const names = new Set();
function clean(sent) {
  if (/["“”'‘’]{1}[A-Z]|[“”"]/.test(sent)) return null;           // quotes = likely a quoted source
  const words = sent.split(/\s+/);
  for (let i = 0; i < words.length; i++) {
    const w = words[i].replace(/[^A-Za-z'’-]/g, '');
    if (/^[A-Z][a-z]/.test(w) && !ALLOW.has(w.replace(/['’]s$/, ''))) { names.add(w.replace(/['’]s$/, '')); return null; }
  }
  return sent;
}
const RISKY = /therap|clinician|trauma|depress|diagnos|medicat|suicid|grief counsel|addict|eating disorder|abuse|drug|psychedel|ayahuasca|alcohol|blood pressure|cholesterol|diabet|supplement|medicine|doctor|milligram|fasting|calorie/i;
const lib = [];
for (const l of letters) {
  const paras = l.body.map(b => strip(b.t));
  const pi = paras.findIndex(p => /^(Today:|In the next 48 hours:)/.test(p));
  if (pi < 0) continue;
  const all = paras.join(' ');
  if (RISKY.test(all) && /clinician|therap/i.test(all)) continue;      // keys that point to a clinician stay out of the guide
  const practice = sentences(paras[pi].replace(/^(Today:|In the next 48 hours:)\s*/, '')).map(clean).filter(Boolean).join(' ');
  let idea = null, best = -1;
  const BAD = /\b(he|she|his|her|him|man|men|woman|women|they|them|their|yesterday|tomorrow|last night|this morning|I|my|me|study|studies|researchers?|title|book|wrote|said|called)\b/i;
  paras.slice(0, pi).forEach((p, pIdx) => sentences(p).forEach(s => {
    const c = clean(s); if (!c || c.length < 25 || c.length > 180 || BAD.test(c)) return;
    let sc = (/^You\b/.test(c) ? 3 : 0) + (/\byou(r)?\b/i.test(c) ? 1 : 0) + (pIdx > 0 ? 1 : 0);
    if (sc > best) { best = sc; idea = c; }
  }));
  if (!idea || !practice || practice.length < 30) continue;
  if (RISKY.test(idea + ' ' + practice)) continue;
  lib.push({ id: `${l.vault[0]}${String(l.key).padStart(3, '0')}-${l.slug}`.slice(0, 60), name: l.title, vault: l.vault, chamber: l.chamber || '', idea, practice: practice.slice(0, 420), url: `/writing/${l.slug}/` });
}
fs.writeFileSync('src/data/guide-keys.js', '// Generated by tools/build_guide_keys.mjs — do not hand-edit. Source names stripped.\nexport default ' + JSON.stringify(lib, null, 1) + ';\n');
// Server-only list of capitalized tokens dropped as possible source names (for the reply validator).
const COMMON = new Set('All Allow Big Book Daily Design Four Games Control Breathing Attending Art Cross Chamber Black White Good Great New Old Small Large Long Short Early Late Real True Free Life Love Home Work Money Time Year Years Week Weeks Day Days Night God Lord Earth World Water Fire Sun Moon Sea Air Light Dark Day One Two Three Six Seven Eight Nine Here There Where What Why How Who Which Most Many Much Some Any Every Never Always Often Sometimes Even Just Only Also Still Yet Already Again Back Down Up Out Over Under Into From With Without About Between Through During Since Until Because While Though Although Unless Whether Both Either Neither Other Another Such Same Different Own Self'.split(' '));
[...names].forEach(n => { if (n.length < 3 || COMMON.has(n)) names.delete(n); });
fs.writeFileSync('functions/api/_guide-names.js', '// Generated: capitalized tokens dropped from Key text as possible source names (validator list).\nexport default ' + JSON.stringify([...names].sort()) + ';\n');
console.log('keys', lib.length, 'of', letters.length, '| name tokens', names.size);
